-- -----------------------------------------------------------------------------
-- websites
-- One row per registered WordPress installation. `credential_hash` stores a
-- SHA-256 digest of the site's bearer token — the raw token is shown to
-- WordPress exactly once, at registration time, and never persisted in
-- plaintext here.
-- -----------------------------------------------------------------------------
create table websites (
  id                 uuid primary key default gen_random_uuid(),
  installation_id    uuid not null,             -- generated by the plugin; NOT unique (cloned sites share it)
  origin             text not null unique,      -- normalized scheme://host[:port]; the site's identity
  owner_user_id      uuid references users(id) on delete set null,
  plan_id            uuid not null references plans(id),
  site_url           text not null,
  site_name          text,
  credential_hash    text not null,
  credential_prefix  text not null,              -- first 8 chars, shown in UI for identification
  credential_rotated_at timestamptz,
  status             text not null default 'active' check (status in ('active', 'suspended', 'revoked')),
  wp_version         text,
  plugin_version     text,
  php_version        text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  last_seen_at       timestamptz
);

create index idx_websites_owner_user_id on websites(owner_user_id);
create index idx_websites_site_url      on websites(site_url);
create index idx_websites_installation_id on websites(installation_id);

create trigger trg_websites_updated_at
  before update on websites
  for each row execute function sg_set_updated_at();


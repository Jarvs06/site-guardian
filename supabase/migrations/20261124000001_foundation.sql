create trigger trg_subscriptions_updated_at
  before update on subscriptions
  for each row execute function sg_set_updated_at();

-- -----------------------------------------------------------------------------
-- credit_balances / credit_transactions
-- The credit ledger. Never write `credit_balances.balance` directly from
-- application code — always go through sg_apply_credit_transaction() so the
-- balance and the transaction row change atomically under a row lock.
-- -----------------------------------------------------------------------------
create table credit_balances (
  website_id  uuid primary key references websites(id) on delete cascade,
  balance     integer not null default 0 check (balance >= 0),
  updated_at  timestamptz not null default now()
);

create table credit_transactions (
  id               uuid primary key default gen_random_uuid(),
  website_id       uuid not null references websites(id) on delete cascade,
  user_id          uuid references users(id) on delete set null,
  scan_job_id      uuid,                         -- FK added once scan_jobs is finalized in Phase 4
  type             text not null check (type in ('grant', 'purchase', 'consume', 'refund', 'adjustment')),
  amount           integer not null,             -- positive = credit added, negative = credit consumed
  balance_before   integer not null,
  balance_after    integer not null,
  description      text,
  idempotency_key  text unique,                  -- prevents double-processing the same billing/scan event
  created_at       timestamptz not null default now()
);

create index idx_credit_transactions_website_id on credit_transactions(website_id, created_at desc);

-- Atomic credit mutation: locks the balance row, validates the resulting
-- balance is never negative, and writes the ledger entry in the same
-- transaction. Callers pass a unique idempotency_key derived from the
-- triggering event (e.g. scan_job id, webhook event id) to make retries safe.
create or replace function sg_apply_credit_transaction(
  p_website_id      uuid,
  p_type            text,
  p_amount          integer,
  p_description      text,
  p_idempotency_key text,
  p_user_id         uuid default null,
  p_scan_job_id     uuid default null
)
returns credit_transactions as $$
declare
  v_balance integer;
  v_existing credit_transactions;
  v_new_balance integer;
  v_row credit_transactions;
begin
  if p_idempotency_key is not null then
    select * into v_existing from credit_transactions where idempotency_key = p_idempotency_key;
    if found then
      return v_existing;
    end if;
  end if;

  insert into credit_balances (website_id, balance)
    values (p_website_id, 0)
    on conflict (website_id) do nothing;

  select balance into v_balance
    from credit_balances
    where website_id = p_website_id
    for update;

  -- Re-check under the lock: a concurrent call with the same key may have
  -- committed while we waited, in which case replay its row.
  if p_idempotency_key is not null then
    select * into v_existing from credit_transactions where idempotency_key = p_idempotency_key;
    if found then
      return v_existing;
    end if;
  end if;

  v_new_balance := v_balance + p_amount;

  if v_new_balance < 0 then
    raise exception 'Insufficient credit balance for website % (balance % + amount % < 0)',
      p_website_id, v_balance, p_amount
      using errcode = 'P0001';
  end if;

  update credit_balances
    set balance = v_new_balance, updated_at = now()
    where website_id = p_website_id;

  insert into credit_transactions (
    website_id, user_id, scan_job_id, type, amount,
    balance_before, balance_after, description, idempotency_key
  ) values (
    p_website_id, p_user_id, p_scan_job_id, p_type, p_amount,
    v_balance, v_new_balance, p_description, p_idempotency_key
  )
  returning * into v_row;

  return v_row;
end;
$$ language plpgsql set search_path = public;

-- -----------------------------------------------------------------------------
-- ai_conversations / ai_messages
-- Server-side conversation memory so a user can leave the Site Guardian page
-- and come back later without losing context.
-- -----------------------------------------------------------------------------
create table ai_conversations (
  id          uuid primary key default gen_random_uuid(),
  website_id  uuid not null references websites(id) on delete cascade,
  user_id     uuid references users(id) on delete set null,
  wp_user_ref text,                          -- opaque per-WordPress-user reference (not a Core user)
  title       text,
  status      text not null default 'active' check (status in ('active', 'archived')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index idx_ai_conversations_website_user
  on ai_conversations(website_id, wp_user_ref, updated_at desc);

create trigger trg_ai_conversations_updated_at
  before update on ai_conversations
  for each row execute function sg_set_updated_at();

create table ai_messages (
  id               uuid primary key default gen_random_uuid(),
  conversation_id  uuid not null references ai_conversations(id) on delete cascade,
  role             text not null check (role in ('user', 'assistant', 'system')),
  content          text not null,
  tool_data        jsonb,                        -- structured scan summaries sent to/from Claude
  created_at       timestamptz not null default now()
);

create index idx_ai_messages_conversation_id on ai_messages(conversation_id, created_at);

-- -----------------------------------------------------------------------------
-- scan_jobs
-- Minimal shell for Phase 1. Full lifecycle (pages, results, pause/resume)
-- is built out in Phase 4/5; this lets ai_conversations reference a job id
-- and lets remote_config/audit_logs exercise real foreign keys today.
-- -----------------------------------------------------------------------------
create table scan_jobs (
  id             uuid primary key default gen_random_uuid(),
  website_id     uuid not null references websites(id) on delete cascade,
  type           text not null check (type in ('link', 'browser', 'performance')),
  status         text not null default 'queued' check (
                   status in ('queued', 'starting', 'running', 'paused', 'completed', 'failed', 'cancelled')
                 ),
  priority       integer not null default 0,
  total          integer not null default 0,
  processed      integer not null default 0,
  attempt_count  integer not null default 0,
  worker_id      text,
  error          text,
  created_at     timestamptz not null default now(),
  started_at     timestamptz,
  completed_at   timestamptz
);

create index idx_scan_jobs_website_id on scan_jobs(website_id, created_at desc);
create index idx_scan_jobs_status     on scan_jobs(status);

alter table credit_transactions
  add constraint fk_credit_transactions_scan_job
  foreign key (scan_job_id) references scan_jobs(id) on delete set null;

-- -----------------------------------------------------------------------------
-- remote_config
-- Key/value config Core serves to every plugin install: UI text overrides,
-- feature flags, maintenance mode, scan limits, announcements, minimum
-- supported plugin version. The plugin always ships safe hardcoded fallback
-- defaults and must never hard-fail if this is unreachable.
-- -----------------------------------------------------------------------------
create table remote_config (
  id           uuid primary key default gen_random_uuid(),
  key          text not null unique,
  value        jsonb not null,
  description  text,
  updated_at   timestamptz not null default now()
);

create trigger trg_remote_config_updated_at
  before update on remote_config
  for each row execute function sg_set_updated_at();

insert into remote_config (key, value, description) values
  ('maintenance_mode', 'false'::jsonb,
    'When true, the plugin shows a maintenance banner and disables AI actions.'),
  ('min_plugin_version', '"0.1.0"'::jsonb,
    'Plugin versions older than this show an update-required notice.'),
  ('scan_limits', '{"link_check_max_urls": 2000, "browser_check_max_pages": 30}'::jsonb,
    'Sitewide default scan limits; per-plan limits in plans.limits take precedence.'),
  ('announcement', 'null'::jsonb,
    'Optional {"text": "...", "level": "info|warning"} shown at the top of the chat page.');

-- -----------------------------------------------------------------------------
-- audit_logs
-- Append-only trail for security-relevant and billing-relevant events
-- (registration, credential rotation, credit mutations, admin actions).
-- -----------------------------------------------------------------------------
create table audit_logs (
  id          uuid primary key default gen_random_uuid(),
  website_id  uuid references websites(id) on delete set null,
  user_id     uuid references users(id) on delete set null,
  wp_user_ref text,
  actor       text not null,               -- 'website:<id>' | 'user:<id>' | 'system' | 'admin:<id>'
  action      text not null,               -- e.g. 'site.registered', 'credit.consumed', 'ai.chat'
  target      text,
  metadata    jsonb not null default '{}'::jsonb,
  ip_address  inet,
  created_at  timestamptz not null default now()
);

create index idx_audit_logs_website_id on audit_logs(website_id, created_at desc);
create index idx_audit_logs_action     on audit_logs(action);

-- -----------------------------------------------------------------------------
-- rate_limits
-- Backing table for rate-limiter-flexible's RateLimiterPostgres, used with
-- `tableName: 'rate_limits', tableCreated: true` (never auto-created at
-- runtime). Column definitions match the library's own CREATE TABLE.
-- -----------------------------------------------------------------------------
create table rate_limits (
  key     varchar(255) primary key,
  points  integer not null default 0,
  expire  bigint                        -- epoch milliseconds; null = never expires
);

create index idx_rate_limits_expire on rate_limits(expire);

-- -----------------------------------------------------------------------------
-- Access control: RLS on every table with NO policies (deny all to anon and
-- authenticated); only the service role (which bypasses RLS) is used by Core.
-- Supabase grants anon/authenticated broad default privileges, so revoke them
-- as well, including for objects created by later migrations.
-- -----------------------------------------------------------------------------
alter table users                    enable row level security;
alter table plans                    enable row level security;
alter table websites                 enable row level security;
alter table registration_challenges  enable row level security;
alter table subscriptions            enable row level security;
alter table credit_balances          enable row level security;
alter table credit_transactions      enable row level security;
alter table ai_conversations         enable row level security;
alter table ai_messages              enable row level security;
alter table scan_jobs                enable row level security;
alter table remote_config            enable row level security;
alter table audit_logs               enable row level security;
alter table rate_limits              enable row level security;

revoke all on all tables    in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
revoke all on all functions in schema public from public, anon, authenticated;

alter default privileges in schema public revoke all on tables    from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;
alter default privileges in schema public revoke all on functions from public, anon, authenticated;

-- Core connects as service_role: keep it fully privileged (explicit, not inherited from defaults).
grant all on all tables    in schema public to service_role;
grant all on all sequences in schema public to service_role;
grant execute on all functions in schema public to service_role;

alter default privileges in schema public grant all on tables    to service_role;
alter default privileges in schema public grant all on sequences to service_role;
alter default privileges in schema public grant execute on functions to service_role;

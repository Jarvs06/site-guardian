-- =============================================================================
-- Site Guardian Core — Stage 1 foundation schema
--
-- Scope: users, plans, websites, subscriptions, credit ledger, AI conversation
-- storage, a minimal scan_jobs shell (full job system arrives in Phase 4/5),
-- remote_config, audit_logs, registration_challenges and rate_limits.
--
-- Everything here is written by Core using the Supabase service-role key.
-- WordPress never talks to this database directly. RLS is enabled on every
-- table with no policies, and anon/authenticated have no privileges at all.
-- =============================================================================

create extension if not exists "pgcrypto";

-- -----------------------------------------------------------------------------
-- Generic updated_at trigger
-- -----------------------------------------------------------------------------
create or replace function sg_set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql set search_path = public;

-- -----------------------------------------------------------------------------
-- users
-- Human account holders. A website can exist without an owning user (an
-- anonymous free install) until it is claimed during signup/billing setup.
-- -----------------------------------------------------------------------------
create table users (
  id            uuid primary key default gen_random_uuid(),
  email         text not null unique,
  display_name  text,
  role          text not null default 'owner' check (role in ('owner', 'admin', 'support')),
  status        text not null default 'active' check (status in ('active', 'disabled')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create trigger trg_users_updated_at
  before update on users
  for each row execute function sg_set_updated_at();

-- -----------------------------------------------------------------------------
-- plans
-- Catalog of subscription tiers. `limits` holds per-plan scan/credit rules
-- (e.g. performance checks per day) so Core can change limits without a
-- WordPress plugin release.
-- -----------------------------------------------------------------------------
create table plans (
  id            uuid primary key default gen_random_uuid(),
  code          text not null unique,          -- 'free' | 'starter' | 'pro' | 'enterprise'
  name          text not null,
  price_cents   integer not null default 0,
  currency      text not null default 'usd',
  limits        jsonb not null default '{}'::jsonb,
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create trigger trg_plans_updated_at
  before update on plans
  for each row execute function sg_set_updated_at();

